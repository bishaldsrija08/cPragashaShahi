// Functions in c are the block of code which performs a specific task. It is a reusable piece of code that can be called multiple times in a program. Functions help in breaking down a large program into smaller and manageable pieces, making it easier to read and maintain.

// Types of functions in C:
// 1. Standard Library Functions: These are built-in functions provided by the C standard library, such as printf(), scanf(), etc.
// 2. User-Defined Functions: These are functions that are defined by the user to perform specific tasks. They can be called multiple times in a program and can take parameters and return values.

#include<stdio.h>
int main(){
    int x;
    printf("Hello World!");
    scanf("%d", &x);
    return 0;
}